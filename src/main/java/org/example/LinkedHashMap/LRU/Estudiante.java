package org.example.LinkedHashMap.LRU;

public class Estudiante {
    String id;
    String nombre;
    String apellido;
    String lenguaje;

    public Estudiante(String id, String nombre, String apellido, String lenguaje){
        this.id = id;
        this.nombre = nombre;
        this.apellido = apellido;
        this.lenguaje = lenguaje;
    }

}
